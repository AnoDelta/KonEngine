        emit("declare i8* @_ks_result_error(i8*)");
        emit("declare i8* @_ks_str_trim(i8*)");
        emit("declare i8* @_ks_str_upper(i8*)");
        emit("declare i8* @_ks_str_lower(i8*)");
        emit("declare i8* @_ks_str_replace(i8*, i8*, i8*)");
